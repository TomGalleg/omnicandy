// "file-exchange" template: the integration writes a file in a documented format that the program can open or import
// (SVG, DXF, OBJ, JSON project files, ...). Nothing is started. CreateCraft's fixed main.js fills the AI's text template with
// validated settings, writes a NEW uniquely named file and checks the format (valid JSON, well-formed XML, or an expected
// pattern). It cannot prove the program accepts the file: that needs a live test with the program.

import type { Blueprint } from '../blueprint';

export function renderFileMain(bp: Blueprint): string {
  const cmds = bp.commands.filter((c) => c.file);
  const table = Object.fromEntries(cmds.map((c) => [c.id, { ...c.file, params: Object.fromEntries(Object.entries(c.params).map(([k, p]) => [k, p.type])) }]));
  const json = JSON.stringify({ appLabel: bp.application.name, commands: table }, null, 2);
  return MAIN_JS.replace('__CONFIG__', () => json);
}

const MAIN_JS = String.raw`'use strict';
// Generated by CreateCraft's AI Adapter Builder from its fixed "file-exchange" template. This file is NOT written by the AI.
// It writes a new file inside the project's work folder (ctx.writeFile) and nothing else: no program is started.

const crypto = require('crypto');

const CONFIG = __CONFIG__;
const STEM = /^[A-Za-z0-9][A-Za-z0-9 _-]{0,59}$/;
// eslint-disable-next-line no-control-regex
const CONTROL = /[\x00-\x1f]/;

exports.probe = async () => ({ version: null, detail: CONFIG.appLabel + ' is not started by this integration; it writes files the program can open.' });
exports.connect = async () => undefined;
exports.healthCheck = async () => ({ ok: true, detail: 'Ready to write files for ' + CONFIG.appLabel + '. The program itself is not started.' });
exports.disconnect = async () => undefined;

function xmlEscape(s) { return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&apos;'); }

function fill(ctx, spec, params) {
  return spec.template.replace(/\{([A-Za-z_][A-Za-z0-9_]{0,40})\}/g, (_m, name) => {
    const type = spec.params[name];
    if (!type) throw ctx.error('invalid-params', 'The template uses {' + name + '} which is not a setting.');
    const v = params[name];
    if (type === 'number') { const n = Number(v); if (!Number.isFinite(n)) throw ctx.error('invalid-params', name + ' must be a number.'); return String(n); }
    if (type === 'boolean') return v ? 'true' : 'false';
    const s = String(v === undefined ? '' : v);
    if (s.length > 200 || CONTROL.test(s)) throw ctx.error('invalid-params', name + ' must be short single-line text.');
    if (spec.check.kind === 'xml') return xmlEscape(s);
    if (spec.check.kind === 'json') return JSON.stringify(s).slice(1, -1);
    return s;
  });
}

function checkFormat(ctx, spec, text) {
  if (spec.check.kind === 'json') {
    try { JSON.parse(text); } catch (e) { throw ctx.error('verification-failed', 'The file is not valid JSON: ' + e.message); }
    return 'valid JSON';
  }
  if (spec.check.kind === 'xml') {
    // A small well-formedness check: balanced, properly nested tags. (It is not a schema check.)
    const stack = [];
    const re = /<(\/?)([A-Za-z_][\w:.-]*)([^>]*?)(\/?)>/g;
    const body = text.replace(/<\?[\s\S]*?\?>/g, '').replace(/<!--[\s\S]*?-->/g, '').replace(/<!\[CDATA\[[\s\S]*?\]\]>/g, '');
    let m;
    while ((m = re.exec(body))) {
      if (m[4] === '/') continue;
      if (m[1] === '/') { if (stack.pop() !== m[2]) throw ctx.error('verification-failed', 'The XML file has mismatched tags near </' + m[2] + '>.'); }
      else stack.push(m[2]);
    }
    if (stack.length) throw ctx.error('verification-failed', 'The XML file has unclosed tags: ' + stack.join(', '));
    return 'well-formed XML';
  }
  if (!new RegExp(spec.check.regex || '.').test(text)) throw ctx.error('verification-failed', 'The file does not match the expected pattern.');
  return 'matches the expected pattern';
}

exports.execute = async (command, params, ctx) => {
  if (command === 'app.health') return { message: 'Ready to write files.', outputs: [], evidence: ['no program is started by this integration'], verified: false };
  const spec = CONFIG.commands[command];
  if (!spec) throw ctx.error('unsupported', 'Unknown command ' + command);
  const stem = String(params[spec.nameParam] === undefined ? '' : params[spec.nameParam]).replace(/\.[A-Za-z0-9]{1,8}$/, '');
  if (!STEM.test(stem)) throw ctx.error('invalid-params', spec.nameParam + ' must be 1 to 60 letters, digits, spaces, "-" or "_".');
  const name = stem + '-' + crypto.randomBytes(3).toString('hex') + spec.extension;
  const text = fill(ctx, spec, params);
  const how = checkFormat(ctx, spec, text);
  if (text.length > 4 * 1024 * 1024) throw ctx.error('app-error', 'The file would be larger than 4 MB.');
  ctx.progress('Writing the file', 0.6);
  await ctx.writeFile(name, text);
  ctx.progress('Done', 1);
  return { message: 'Wrote ' + name + '. Open or import it in ' + CONFIG.appLabel + '.', outputs: [name], data: { bytes: text.length }, evidence: ['the file content is ' + how], verified: false };
};
`;
