// "cli" template: the program is driven through its documented command line. The AI supplies, per command, a fixed argument
// list with {name} tokens and a rule for each token. OmniCandy's fixed main.js substitutes validated values as separate
// arguments (never through a shell), starts only the discovered program, checks the exit code and expected output files, and
// can run a second read-only command (for example "identify") to check the result independently.

import type { Blueprint, BlueprintCommand } from '../blueprint';

export const TOKEN_RE = /\{([A-Za-z_][A-Za-z0-9_]{0,40})\}/g;
// eslint-disable-next-line no-control-regex -- control characters are exactly what is being rejected
const LITERAL_BAD = /[\x00-\x1f"'`$&|;<>^\\]/;
const FLAG_DENY = /^(-?-?(exec|script|eval|execute|run|shell|command|cmd)|-c|-e|\/c|\/k|-write|--write)$/i;

/** Problems with one argument list; empty when it is acceptable. */
export function argvProblems(argv: string[], rules: Record<string, { kind: string; extensions?: string[]; values?: string[] }>, label: string): string[] {
  const out: string[] = [];
  argv.forEach((t, i) => {
    const tokens = [...t.matchAll(TOKEN_RE)];
    if (tokens.length > 1) out.push(`${label}: argument ${i + 1} ("${t}") has more than one {setting}.`);
    const literal = t.replace(TOKEN_RE, '');
    if (LITERAL_BAD.test(literal)) out.push(`${label}: argument ${i + 1} ("${t}") contains a character that is not allowed in a fixed argument.`);
    if (/^@/.test(t) || /:\/\//.test(t) || /^[A-Za-z]:[\\/]/.test(t) || /^[\\/]/.test(t) || /(^|[\\/])\.\.($|[\\/])/.test(t)) out.push(`${label}: argument ${i + 1} ("${t}") reads a list file, a URL or a path outside the work folder.`);
    if (FLAG_DENY.test(t)) out.push(`${label}: argument ${i + 1} ("${t}") would run text or another program.`);
    if (/^\{/.test(t) && tokens.length === 1 && t !== tokens[0]![0]) out.push(`${label}: argument ${i + 1}: a setting must stand alone or follow a fixed prefix such as --size={size}.`);
    for (const m of tokens) {
      const rule = rules[m[1]!];
      if (!rule) out.push(`${label}: argument ${i + 1} uses {${m[1]}} but no rule describes it.`);
      else if (rule.kind === 'enum' && !(rule.values?.length)) out.push(`${label}: {${m[1]}} is an enum without values.`);
      else if ((rule.kind === 'work-file-in' || rule.kind === 'work-file-out') && !(rule.extensions?.length)) out.push(`${label}: {${m[1]}} is a file setting without allowed extensions.`);
    }
  });
  return out;
}

export function renderCliMain(bp: Blueprint): string {
  const cmds = bp.commands.filter((c) => c.cli);
  const table = Object.fromEntries(cmds.map((c: BlueprintCommand) => [c.id, c.cli]));
  const config = {
    versionArgs: bp.cli?.versionArgs ?? ['--version'],
    versionRegex: bp.cli?.versionRegex ?? '(\\d+(?:\\.\\d+){1,2})',
    appLabel: bp.application.name,
    commands: table,
  };
  const json = JSON.stringify(config, null, 2);
  return MAIN_JS.replace('__CONFIG__', () => json);
}

const MAIN_JS = String.raw`'use strict';
// Generated by OmniCandy's AI Adapter Builder from its fixed "cli" template. This file is NOT written by the AI.
// It runs in OmniCandy's restricted adapter process. The program is started by OmniCandy (ctx.runApp), never through a shell,
// and each argument is either a fixed word below or ONE validated value. Output files always get a fresh unique name, so nothing
// that already exists in the project is overwritten.

const crypto = require('crypto');

const CONFIG = __CONFIG__;
const KINDS = new Set(['app-error', 'unsupported', 'invalid-params', 'missing-app', 'verification-failed']);
const TOKEN = /\{([A-Za-z_][A-Za-z0-9_]{0,40})\}/g;
const STEM = /^[A-Za-z0-9][A-Za-z0-9 _-]{0,59}$/;
const NAME = /^[A-Za-z0-9][A-Za-z0-9 _.-]{0,80}$/;
const TEXT = /^[A-Za-z0-9][A-Za-z0-9 _.,:()%+x-]{0,119}$/;
const tail = (s) => String(s || '').trim().split(/\r?\n/).slice(-4).join(' ').slice(0, 400);
const lowerExt = (n) => { const i = n.lastIndexOf('.'); return i < 0 ? '' : n.slice(i).toLowerCase(); };

async function version(ctx) {
  const r = await ctx.runApp(CONFIG.versionArgs, { timeoutMs: 60000 });
  const m = new RegExp(CONFIG.versionRegex, 'i').exec(r.out + '\n' + r.err);
  if (!m) throw ctx.error('app-error', 'The program did not report a version (exit ' + r.code + '). ' + tail(r.err || r.out));
  return m[1];
}

exports.probe = async (ctx) => { const v = await version(ctx); return { version: v, detail: CONFIG.appLabel + ' ' + v + '.' }; };
exports.connect = async () => undefined;
exports.healthCheck = async (ctx) => {
  try { const v = await version(ctx); return { ok: true, detail: CONFIG.appLabel + ' answers (version ' + v + ').' }; }
  catch (e) { return { ok: false, detail: String((e && e.message) || e) }; }
};
exports.disconnect = async () => undefined;

/** Turns the validated settings into final values, once per command run (output names are unique per run). */
function resolveValues(ctx, spec, params) {
  const out = {};
  for (const [name, rule] of Object.entries(spec.rules)) {
    const v = params[name];
    if (v === undefined || v === null || v === '') { out[name] = null; continue; }
    if (rule.kind === 'number') {
      const n = Number(v);
      if (!Number.isFinite(n)) throw ctx.error('invalid-params', name + ' must be a number.');
      out[name] = String(n);
    } else if (rule.kind === 'enum') {
      if (!(rule.values || []).includes(String(v))) throw ctx.error('invalid-params', name + ' must be one of: ' + (rule.values || []).join(', ') + '.');
      out[name] = String(v);
    } else if (rule.kind === 'text') {
      if (!TEXT.test(String(v))) throw ctx.error('invalid-params', name + ' may only use letters, digits, spaces and . , : ( ) % + x - (and must start with a letter or digit).');
      out[name] = String(v);
    } else if (rule.kind === 'work-file-in') {
      const s = String(v);
      if (!NAME.test(s) || s.indexOf('..') >= 0 || !(rule.extensions || []).map((e) => e.toLowerCase()).includes(lowerExt(s))) throw ctx.error('invalid-params', name + ' must be a plain file name in the project work folder ending in ' + (rule.extensions || []).join(' or ') + '.');
      out[name] = s;
    } else if (rule.kind === 'work-file-out') {
      const s = String(v).replace(/\.[A-Za-z0-9]{1,8}$/, '');
      if (!STEM.test(s)) throw ctx.error('invalid-params', name + ' must be 1 to 60 letters, digits, spaces, "-" or "_".');
      out[name] = s + '-' + crypto.randomBytes(3).toString('hex') + (rule.extensions || ['.out'])[0];
    }
  }
  return out;
}

function build(ctx, argv, values) {
  const args = [];
  for (const t of argv) {
    let skip = false;
    const s = t.replace(TOKEN, (_m, name) => { const v = values[name]; if (v === null || v === undefined) { skip = true; return ''; } return v; });
    // An optional setting that was not given drops its whole argument (and a flag that only exists to introduce it is the AI's to avoid).
    if (!skip) args.push(s);
  }
  return args;
}

exports.execute = async (command, params, ctx) => {
  if (command === 'app.health') {
    const v = await version(ctx);
    return { message: CONFIG.appLabel + ' ' + v + ' answered a real command-line call.', outputs: [], data: { version: v }, evidence: ['ran ' + CONFIG.versionArgs.join(' ') + ' and read version ' + v], verified: true };
  }
  const spec = CONFIG.commands[command];
  if (!spec) throw ctx.error('unsupported', 'Unknown command ' + command);
  const values = resolveValues(ctx, spec, params);
  const args = build(ctx, spec.argv, values);
  ctx.progress('The program is working', 0.3);
  const r = await ctx.runApp(args, { timeoutMs: 600000 });
  if (ctx.signal.aborted) throw ctx.error('app-error', 'The operation was cancelled.');
  if (!spec.expect.exitCodes.includes(r.code === null ? -1 : r.code)) throw ctx.error('app-error', 'The program reported an error (exit ' + r.code + '). ' + tail(r.err || r.out));
  if (spec.expect.stdoutRegex && !new RegExp(spec.expect.stdoutRegex).test(r.out)) throw ctx.error('verification-failed', 'The program\'s output did not look as expected. ' + tail(r.out));
  const outputs = spec.outputs.map((o) => o.replace(TOKEN, (_m, name) => values[name] || '')).filter((o) => o);
  const evidence = ['the program finished with exit code ' + r.code];
  let verified = false;
  if (spec.verify) {
    ctx.progress('Checking the result in a separate call', 0.8);
    const vr = await ctx.runApp(build(ctx, spec.verify.argv, values), { timeoutMs: 120000 });
    if (vr.code !== 0 || !new RegExp(spec.verify.stdoutRegex).test(vr.out)) throw ctx.error('verification-failed', 'The independent check did not confirm the result. ' + tail(vr.err || vr.out));
    evidence.push('independent check: ' + tail(vr.out));
    verified = true;
  }
  ctx.progress('Done', 1);
  return { message: 'Done. ' + (outputs.length ? 'Created ' + outputs.join(', ') + '.' : ''), outputs, data: { exitCode: r.code, stdout: tail(r.out) }, evidence, verified };
};
`;
