/** Structured, advisory task plan. Only application tools may modify user documents. */
import { z } from 'zod';
import { tool, type ToolRegistry } from './registry';
export const stepSchema = z.object({
  id: z.string().regex(/^[a-zA-Z0-9_-]{1,48}$/),
  title: z.string().trim().min(1).max(180),
  status: z.enum(['pending','active','completed','blocked']),
  evidence: z.string().max(1000).optional(),
  receiptIds: z.array(z.string().regex(/^r[1-9][0-9]*$/)).max(10).optional(),
  verificationIds: z.array(z.string().regex(/^v[1-9][0-9]*$/)).max(10).optional(),
});
export const planSchema = z.object({
  goal: z.string().min(1).max(4000),
  steps: z.array(stepSchema).max(20),
});
export type TaskPlan = z.infer<typeof planSchema>;
export const clonePlan = (plan: TaskPlan): TaskPlan => structuredClone(planSchema.parse(plan));
export interface ApplicationReceipt { id: string; tool: string; summary: string; verified: boolean; command?: string; readback?: boolean; saveVersionId?: string }
export interface EvidenceCheck { id: string; sourceReceiptId: string; path: string; expected: string | number | boolean | null; observed: unknown; passed: boolean }
/** Only known native inspection commands qualify. Other command results are execution receipts,
 * never independently verified read-back. External adapters need explicit read-only metadata first. */
const confirmedSave = (text: string): string | undefined => {
  try {
    const value: unknown = JSON.parse(text);
    if (!value || typeof value !== 'object' || Array.isArray(value)) return;
    const entry = value as Record<string, unknown>;
    return entry.saved === true && typeof entry.versionId === 'string' && entry.versionId.length > 0 && entry.versionId.length <= 160 ? entry.versionId : undefined;
  } catch { return; }
};
const readOnlyNativeCommands = new Set(['shape.info', 'layer.list', 'document.inspect']);
const parseReadback = (text: string): unknown => {
  const marker = text.indexOf('\nResult: ');
  const raw = marker >= 0 ? text.slice(marker + '\nResult: '.length).trim() : text.startsWith('Result: ') ? text.slice('Result: '.length).trim() : text.trim();
  try { return JSON.parse(raw); } catch { return undefined; }
};
const field = (root: unknown, path: string): { exists: boolean; value?: unknown } => {
  let cur: unknown = root;
  for (const part of path.split('.')) {
    if (cur === null || typeof cur !== 'object' || !Object.prototype.hasOwnProperty.call(cur, part)) return {exists:false};
    cur = (cur as Record<string, unknown>)[part];
  }
  return { exists:true, value:cur };
};
/** Receipts are generated by the runner, never accepted from model output. They
 * establish that a tool returned successfully, NOT that the goal was achieved. */
export function registerTaskPlan(registry: ToolRegistry, initialGoal: string, initialPlan: TaskPlan | undefined, onChange: (plan: TaskPlan) => void) {
  let plan: TaskPlan = initialPlan ? clonePlan(initialPlan) : {goal: initialGoal,steps:[]};
  const publish = () => onChange(clonePlan(plan));
  const receipts: ApplicationReceipt[] = [];
  let nextReceipt = 1;
  const readbacks = new Map<string, unknown>();
  const checks: EvidenceCheck[] = [];
  let nextCheck = 1;
  registry.remove('evidence_receipts');
  registry.add(tool('evidence_receipts', 'List recent successful application-tool results. Receipt IDs attest only to execution, not verified visual or document outcomes.', z.object({}).strict(), async () => ({text:JSON.stringify(receipts.slice(-30)),verified:false})));
  const record = (toolName: string, text: string, verified: boolean, args?: unknown): string | undefined => {
    if (!['app_command','external_command','look_at_document','new_document','save_version'].includes(toolName)) return;
    // Save receipts are accepted only with a structured new-version confirmation.
    const saveVersionId = toolName === 'save_version' ? confirmedSave(text) : undefined;
    if (toolName === 'save_version' && !saveVersionId) return;
    const id = `r${nextReceipt++}`;
    const cmd = toolName === 'app_command' && args && typeof args === 'object' && !Array.isArray(args)
      ? (args as Record<string, unknown>).command : undefined;
    const command = typeof cmd === 'string' ? cmd : undefined;
    const parsed = command && readOnlyNativeCommands.has(command) ? parseReadback(text) : undefined;
    if (parsed !== undefined) readbacks.set(id, parsed);
    receipts.push({id,tool:toolName,summary:text.slice(0,240),verified,command,readback:parsed !== undefined,...(saveVersionId ? {saveVersionId} : {})});
    if (receipts.length > 100) { const removed=receipts.shift(); if (removed) readbacks.delete(removed.id); }
    return id;
  };
  registry.remove('evidence_verify');
  registry.add(tool('evidence_verify', 'Independently compare a primitive expected value against structured JSON from a successful read-only application inspection receipt (currently shape.info, layer.list, document.inspect). Does not execute or edit anything. Only a passing check counts as a verified read-back; other receipts prove tool execution only.',
    z.object({receipt_id:z.string().regex(/^r[1-9][0-9]*$/),path:z.string().regex(/^[a-zA-Z_][a-zA-Z0-9_]*(\.(?:[a-zA-Z_][a-zA-Z0-9_]*|[0-9]+))*$/).max(160),expected:z.union([z.string().max(500),z.number().finite(),z.boolean(),z.null()]),tolerance:z.number().min(0).max(1000000).optional()}).strict(),
    async ({receipt_id,path,expected,tolerance}) => {
      if (!readbacks.has(receipt_id)) return {text:'Error: Receipt has no eligible structured read-back; use an approved read-only inspection command.',isError:true};
      const found=field(readbacks.get(receipt_id),path);
      if (!found.exists) return {text:`Verification unavailable: ${path} not present in read-back ${receipt_id}.`,verified:false};
      const observed=found.value;
      const passed = tolerance !== undefined && typeof observed === 'number' && typeof expected === 'number'
        ? Number.isFinite(observed) && Math.abs(observed-expected)<=tolerance
        : (observed === expected);
      const check: EvidenceCheck={id:`v${nextCheck++}`,sourceReceiptId:receipt_id,path,expected,observed,passed};
      checks.push(check);if(checks.length>100)checks.shift();
      return {text:JSON.stringify(check),verified:passed};
    }));
  registry.remove('task_plan');
  registry.add(tool('task_plan', 'Create or update task plan steps. Newly completed steps require a passing evidence_verify ID, or for a save step a confirmed save_version receipt. Previously completed steps are grandfathered on resume. Tool execution alone and prose are NOT proof. Keep IDs stable.',
    z.object({steps:z.array(stepSchema).min(1).max(20)}), async ({steps}) => {
      const ids = steps.map(s=>s.id);
      if (new Set(ids).size !== ids.length) return {text:'Error: Task step IDs must be unique.',isError:true};
      // Evidence is required when claiming verified completion, even if no visual preview is possible.
      const unsupported = steps.find(s=>s.status==='completed' && !s.evidence?.trim());
      if (unsupported) return {text:`Error: Completed step ${unsupported.id} needs read-back evidence.`,isError:true};
      for (const step of steps) {
        const previous = plan.steps.find(s => s.id === step.id);
        if (step.status === 'completed' && previous?.status !== 'completed') {
          const validVerification = (step.verificationIds ?? []).some(id => checks.some(c => c.id === id && c.passed));
          const confirmedVersion = (step.receiptIds ?? []).some(id => receipts.some(r => r.id === id && r.tool === 'save_version' && r.saveVersionId));
          const saveStep = /\b(save|saved|saving|version|export)\b/i.test(step.title);
          if (saveStep && !confirmedVersion)
            return {text:`Error: Save step ${step.id} requires a confirmed new-version save_version receipt; a read-back comparison alone cannot confirm saving.`,isError:true};
          if (!validVerification && !confirmedVersion)
            return {text:`Error: Newly completed step ${step.id} requires a passing evidence_verify ID or a confirmed save_version receipt. Model prose or edit receipts are not independent evidence.`,isError:true};
        }
        for (const id of step.verificationIds ?? []) {
          const existed = plan.steps.find(s => s.id === step.id)?.verificationIds?.includes(id);
          if (!existed && !checks.some(c => c.id === id && c.passed))
            return {text:`Error: Verification ${id} is missing, failed, or not from an approved read-back.`,isError:true};
        }
        for (const id of step.receiptIds ?? []) {
          const existed = plan.steps.find(s => s.id === step.id)?.receiptIds?.includes(id);
          if (!existed && !receipts.some(r => r.id === id))
            return {text:`Error: Unknown or unsuccessful tool receipt ${id}.`,isError:true};
        }
      }
      plan={goal:initialGoal,steps:structuredClone(steps)};
      publish();
      return {text:`Task plan recorded (${steps.length} steps). A plan is not evidence of application changes.`,verified:false};
    }));
  return {snapshot:()=>clonePlan(plan),record};
}

/** Validate human plan edits before encrypted persistence. */
export function validatePlanEdit(goal: string, steps: TaskPlan['steps']): TaskPlan {
  const plan = planSchema.parse({goal, steps});
  if (new Set(plan.steps.map(step => step.id)).size !== plan.steps.length)
    throw new Error('Task step IDs must be unique.');
  if (plan.steps.some(step => step.status === 'completed' && !step.evidence?.trim()))
    throw new Error('Completed steps require verification evidence.');
  return clonePlan(plan);
}
