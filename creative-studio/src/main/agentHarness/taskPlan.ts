/** Structured, advisory task plan. Only application tools may modify user documents. */
import { z } from 'zod';
import type { ExpectedEdit } from './editIntentJournal';
import { assessBatchReadback, type BatchAssessment } from '../integrations/adapters/blenderBatchSpec';
import { assessScriptReadback, type ScriptAssessment } from '../integrations/adapters/blenderScriptSpec';
import { NATIVE_READBACK_COMMANDS } from './nativeReadback';
import { PATH_SHAPE, compareEvidence, parseEvidencePath, resolveEvidencePath, summarizeObserved, MAX_EXPECTED_ITEMS, MAX_PATH_LENGTH, type Primitive } from './evidencePath';
import { tool, type ToolRegistry } from './registry';
export const stepSchema = z.object({
  id: z.string().regex(/^[a-zA-Z0-9_-]{1,48}$/),
  title: z.string().trim().min(1).max(180),
  status: z.enum(['pending','active','completed','blocked']),
  evidence: z.string().max(1000).optional(),
  receiptIds: z.array(z.string().regex(/^r[1-9][0-9]*$/)).max(10).optional(),
  verificationIds: z.array(z.string().regex(/^v[1-9][0-9]*$/)).max(10).optional(),
});
export const planSchema = z.object({
  goal: z.string().min(1).max(4000),
  steps: z.array(stepSchema).max(20),
});
export type TaskPlan = z.infer<typeof planSchema>;
export const clonePlan = (plan: TaskPlan): TaskPlan => structuredClone(planSchema.parse(plan));
export interface ApplicationReceipt { id: string; tool: string; summary: string; verified: boolean; command?: string; /** External read-backs: the file the inspection was about. */ file?: string; readback?: boolean; saveVersionId?: string }
export interface EvidenceCheck { id: string; sourceReceiptId: string; path: string; expected: Primitive | Primitive[]; observed: unknown; passed: boolean }
/** Only known native inspection commands qualify. Other command results are execution receipts,
 * never independently verified read-back. External adapters need explicit read-only metadata first. */
const confirmedSave = (text: string): string | undefined => {
  try {
    const value: unknown = JSON.parse(text);
    if (!value || typeof value !== 'object' || Array.isArray(value)) return;
    const entry = value as Record<string, unknown>;
    return entry.saved === true && typeof entry.versionId === 'string' && entry.versionId.length > 0 && entry.versionId.length <= 160 ? entry.versionId : undefined;
  } catch { return; }
};
const readOnlyNativeCommands = NATIVE_READBACK_COMMANDS;
/** The first COMPLETE JSON object/array at the start of `raw`, located by a string-aware bracket scan. Anything after it must
 * start on a new line (PhotoCraft appends diagnostics such as "Parameter validation unavailable: ..."): that text is ignored
 * and is never evidence. Partial JSON, or junk glued to the closing bracket, yields undefined. */
const firstJsonValue = (raw: string): string | undefined => {
  if (raw[0] !== '{' && raw[0] !== '[') return;
  let depth = 0, inString = false, escaped = false;
  for (let i = 0; i < raw.length; i++) {
    const ch = raw[i]!;
    if (inString) { if (escaped) escaped = false; else if (ch === '\\') escaped = true; else if (ch === '"') inString = false; continue; }
    if (ch === '"') inString = true;
    else if (ch === '{' || ch === '[') depth++;
    else if (ch === '}' || ch === ']') {
      depth--;
      if (depth === 0) { const rest = raw.slice(i + 1); return rest === '' || /^\s/.test(rest) ? raw.slice(0, i + 1) : undefined; }
      if (depth < 0) return;
    }
  }
  return;
};
const parseReadback = (text: string): unknown => {
  const marker = text.indexOf('\nResult: ');
  const raw = marker >= 0 ? text.slice(marker + '\nResult: '.length).trim() : text.startsWith('Result: ') ? text.slice('Result: '.length).trim() : text.trim();
  const json = firstJsonValue(raw);
  if (json === undefined) return undefined;
  try { return JSON.parse(json); } catch { return undefined; }
};
const field = (root: unknown, path: string): { exists: boolean; value?: unknown } => {
  const tokens = parseEvidencePath(path);
  if (!tokens) return { exists:false };
  const r = resolveEvidencePath(root, tokens);
  return r.exists ? { exists:true, value:r.value } : { exists:false };
};
const matchesRect = (doc: unknown, layer: number, rect: readonly number[]): boolean => {
  const reportedLayer = field(doc, 'layer');
  if (!reportedLayer.exists || reportedLayer.value !== layer) return false;
  return rect.length === 4 && rect.every((n,i) => field(doc, `live.rect.${i}`).value === n && field(doc,`live.rect.${i}`).exists);
};
/** Receipts are generated by the runner, never accepted from model output. They
 * establish that a tool returned successfully, NOT that the goal was achieved. */
export function registerTaskPlan(registry: ToolRegistry, initialGoal: string, initialPlan: TaskPlan | undefined, onChange: (plan: TaskPlan) => void) {
  let plan: TaskPlan = initialPlan ? clonePlan(initialPlan) : {goal: initialGoal,steps:[]};
  const publish = () => onChange(clonePlan(plan));
  const receipts: ApplicationReceipt[] = [];
  let nextReceipt = 1;
  const readbacks = new Map<string, unknown>();
  const checks: EvidenceCheck[] = [];
  let nextCheck = 1;
  registry.remove('evidence_receipts');
  registry.add(tool('evidence_receipts', 'List recent successful application-tool results. Receipt IDs attest only to execution, not verified visual or document outcomes.', z.object({}).strict(), async () => ({text:JSON.stringify(receipts.slice(-30)),verified:false})));
  // `trustedReadback` comes from the host (a built-in adapter's read-only command), never from model output or a command's own `verified` claim.
  const record = (toolName: string, text: string, verified: boolean, args?: unknown, trustedReadback = false, structured?: unknown): string | undefined => {
    if (!['app_command','external_command','photocraft_command','timeline_add','timeline_move_clip','timeline_remove_clip','look_at_document','new_document','save_version'].includes(toolName) && !(toolName === 'get_status' && trustedReadback)) return;
    // Save receipts are accepted only with a structured new-version confirmation.
    const saveVersionId = toolName === 'save_version' ? confirmedSave(text) : undefined;
    if (toolName === 'save_version' && !saveVersionId) return;
    const id = `r${nextReceipt++}`;
    const argRecord = args && typeof args === 'object' && !Array.isArray(args) ? args as Record<string, unknown> : undefined;
    const cmd = (toolName === 'app_command' || toolName === 'external_command') ? argRecord?.command : undefined;
    const command = typeof cmd === 'string' ? cmd : undefined;
    const params = argRecord?.params && typeof argRecord.params === 'object' && !Array.isArray(argRecord.params) ? argRecord.params as Record<string, unknown> : undefined;
    const file = toolName === 'external_command' && typeof params?.file_name === 'string' ? params.file_name.slice(0, 200) : undefined;
    // Structured state attached by the host (large read-backs) wins over the possibly summarized model-visible text.
    const nativeRead = toolName === 'app_command' && !!command && readOnlyNativeCommands.has(command);
    const parsed = nativeRead ? parseReadback(text)
      : trustedReadback && (toolName === 'external_command' || toolName === 'get_status') ? (structured !== undefined ? structured : parseReadback(text)) : undefined;
    if (parsed !== undefined) readbacks.set(id, parsed);
    receipts.push({id,tool:toolName,summary:text.slice(0,240),verified,command,...(file ? {file} : {}),readback:parsed !== undefined,...(saveVersionId ? {saveVersionId} : {})});
    if (receipts.length > 100) { const removed=receipts.shift(); if (removed) readbacks.delete(removed.id); }
    return id;
  };
  registry.remove('evidence_verify');
  registry.add(tool('evidence_verify', 'Independently compare an expected value against structured JSON from a successful read-only inspection receipt (shape.info, layer.list, get_status, or a trusted external inspection such as Blender scene.inspect). Does not execute or edit anything. Only a passing check counts as a verified read-back; other receipts prove tool execution only. path: dotted keys and indexes (data.details.1.location.0), brackets (data.details[1].location[0]), or select an array element by a key (data.details[name=Cube].materials[0].color). expected: a string/number/boolean/null, or an array of up to 16 of them to compare a whole vector (location [3,0,0]); numbers match within tolerance; "#rrggbb" matches a colour array (channels 0..1, default tolerance 0.002).',
    z.object({receipt_id:z.string().regex(/^r[1-9][0-9]*$/),path:z.string().regex(PATH_SHAPE).max(MAX_PATH_LENGTH),expected:z.union([z.string().max(500),z.number().finite(),z.boolean(),z.null(),z.array(z.union([z.string().max(200),z.number().finite(),z.boolean(),z.null()])).min(1).max(MAX_EXPECTED_ITEMS)]),tolerance:z.number().min(0).max(1000000).optional()}).strict(),
    async ({receipt_id,path,expected,tolerance}) => {
      if (!readbacks.has(receipt_id)) return {text:'Error: Receipt has no eligible structured read-back; use an approved read-only inspection command.',isError:true};
      const tokens = parseEvidencePath(path);
      if (!tokens) return {text:'Error: Unsupported path. Use dotted keys and indexes, [n] indexes, or [key=value] selectors (at most 12 steps).',isError:true};
      // An external result envelope carries the command's own claims (verified, message, evidence); only its returned state may be compared.
      const first = tokens[0];
      if (receipts.find(r => r.id === receipt_id)?.tool === 'external_command' && !(first && 'key' in first && first.key === 'data' && tokens.length > 1))
        return {text:'Error: For external read-backs compare fields under data.* only; the command\'s own verified/message/evidence fields are claims, not state.',isError:true};
      const found=resolveEvidencePath(readbacks.get(receipt_id),tokens);
      if (!found.exists) return {text:`Verification unavailable: ${path} not usable in read-back ${receipt_id}${found.reason ? ` (${found.reason})` : ''}.`,verified:false};
      const observed=found.value;
      const passed = compareEvidence(observed, expected as Primitive | Primitive[], tolerance);
      const check: EvidenceCheck={id:`v${nextCheck++}`,sourceReceiptId:receipt_id,path,expected:expected as Primitive | Primitive[],observed:summarizeObserved(observed),passed};
      checks.push(check);if(checks.length>100)checks.shift();
      return {text:JSON.stringify(check),verified:passed};
    }));
  registry.remove('task_plan');
  registry.add(tool('task_plan', 'Create or update task plan steps. Newly completed steps require a passing evidence_verify ID, or for a save step a confirmed save_version receipt. Previously completed steps are grandfathered on resume. Tool execution alone and prose are NOT proof. Keep IDs stable.',
    z.object({steps:z.array(stepSchema).min(1).max(20)}), async ({steps}) => {
      const ids = steps.map(s=>s.id);
      if (new Set(ids).size !== ids.length) return {text:'Error: Task step IDs must be unique.',isError:true};
      // Evidence is required when claiming verified completion, even if no visual preview is possible.
      const unsupported = steps.find(s=>s.status==='completed' && !s.evidence?.trim());
      if (unsupported) return {text:`Error: Completed step ${unsupported.id} needs read-back evidence.`,isError:true};
      for (const step of steps) {
        const previous = plan.steps.find(s => s.id === step.id);
        if (step.status === 'completed' && previous?.status !== 'completed') {
          const validVerification = (step.verificationIds ?? []).some(id => checks.some(c => c.id === id && c.passed));
          const confirmedVersion = (step.receiptIds ?? []).some(id => receipts.some(r => r.id === id && r.tool === 'save_version' && r.saveVersionId));
          const saveStep = /\b(save|saved|saving|version|export)\b/i.test(step.title);
          if (saveStep && !confirmedVersion)
            return {text:`Error: Save step ${step.id} requires a confirmed new-version save_version receipt; a read-back comparison alone cannot confirm saving.`,isError:true};
          if (!validVerification && !confirmedVersion)
            return {text:`Error: Newly completed step ${step.id} requires a passing evidence_verify ID or a confirmed save_version receipt. Model prose or edit receipts are not independent evidence.`,isError:true};
        }
        for (const id of step.verificationIds ?? []) {
          const existed = plan.steps.find(s => s.id === step.id)?.verificationIds?.includes(id);
          if (!existed && !checks.some(c => c.id === id && c.passed))
            return {text:`Error: Verification ${id} is missing, failed, or not from an approved read-back.`,isError:true};
        }
        for (const id of step.receiptIds ?? []) {
          const existed = plan.steps.find(s => s.id === step.id)?.receiptIds?.includes(id);
          if (!existed && !receipts.some(r => r.id === id))
            return {text:`Error: Unknown or unsuccessful tool receipt ${id}.`,isError:true};
        }
      }
      plan={goal:initialGoal,steps:structuredClone(steps)};
      publish();
      return {text:`Task plan recorded (${steps.length} steps). A plan is not evidence of application changes.`,verified:false};
    }));
  return {snapshot:()=>clonePlan(plan),record,
    isReadbackReceipt: (id: string) => readbacks.has(id),
    latestPassingCheck: () => [...checks].reverse().find(c => c.passed),
    /** True when the stored trusted read-back shows the recorded expected outcome. Unknown kinds never match. */
    matchesExpectedEdit: (receiptId: string, expected: ExpectedEdit): boolean => {
      const receipt = receipts.find(r => r.id === receiptId);
      const doc = readbacks.get(receiptId);
      if (!receipt || doc === undefined) return false;
      if (expected.kind === 'photocraft.shape.edit.rect') return receipt.command === 'shape.info' && matchesRect(doc, expected.layer, expected.rect);
      if (expected.kind === 'blender.script.run') return receipt.tool === 'external_command' && receipt.command === 'scene.inspect_detail' && assessScriptReadback(doc, expected).releasesLock;
      if (expected.kind === 'blender.scene.batch') return receipt.tool === 'external_command' && receipt.command === 'scene.inspect_detail' && assessBatchReadback(doc, expected).releasesLock;
      if (receipt.tool !== 'external_command' || (receipt.command !== 'scene.inspect' && receipt.command !== 'scene.inspect_detail') || receipt.file !== expected.file) return false;
      const details = field(doc, 'data.details');
      if (!details.exists || !Array.isArray(details.value)) return false;
      const entries = details.value.filter((d): d is Record<string, unknown> => !!d && typeof d === 'object' && (d as Record<string, unknown>).name === expected.object);
      if (entries.length !== 1) return false;
      const entry = entries[0]!;
      if (expected.kind === 'blender.object.transform') {
        const source: Record<string, [string, number, number]> = { x:['location',0,0.0006], y:['location',1,0.0006], z:['location',2,0.0006], rx:['rotation_deg',0,0.011], ry:['rotation_deg',1,0.011], rz:['rotation_deg',2,0.011], sx:['scale',0,0.0006], sy:['scale',1,0.0006], sz:['scale',2,0.0006] };
        return Object.entries(expected.values).every(([axis, want]) => {
          const [key, index, tolerance] = source[axis]!;
          const list = entry[key];
          const got = Array.isArray(list) ? list[index] : undefined;
          return typeof got === 'number' && Math.abs(got - want) <= tolerance;
        });
      }
      const rgb = [1, 3, 5].map(i => parseInt(expected.color.slice(i, i + 2), 16) / 255);
      const materials = entry.materials;
      return Array.isArray(materials) && materials.some(m => {
        const c = m && typeof m === 'object' ? (m as Record<string, unknown>).color : undefined;
        return Array.isArray(c) && rgb.every((v, i) => typeof c[i] === 'number' && Math.abs((c[i] as number) - v) <= 0.002);
      });
    },
    /** What a stored trusted read-back says about a recorded Blender batch (applied / absent / partial / ambiguous). */
    assessExpectedEdit: (receiptId: string, expected: ExpectedEdit): BatchAssessment | ScriptAssessment | undefined => {
      const receipt = receipts.find(r => r.id === receiptId);
      const doc = readbacks.get(receiptId);
      if ((expected.kind !== 'blender.scene.batch' && expected.kind !== 'blender.script.run') || !receipt || doc === undefined || receipt.tool !== 'external_command' || receipt.command !== 'scene.inspect_detail') return undefined;
      return expected.kind === 'blender.script.run' ? assessScriptReadback(doc, expected) : assessBatchReadback(doc, expected);
    },
    matchesRecordedRect: (receiptId: string, layer: number, rect: readonly number[]): boolean => {
      const doc = readbacks.get(receiptId);
      if (!doc || !receipts.some(r => r.id === receiptId && r.command === 'shape.info')) return false;
      const reportedLayer = field(doc, 'layer');
      if (!reportedLayer.exists || reportedLayer.value !== layer) return false;
      return rect.length === 4 && rect.every((n,i) => field(doc, `live.rect.${i}`).value === n && field(doc,`live.rect.${i}`).exists);
    },
  };
}

/** Validate human plan edits before encrypted persistence. */
export function validatePlanEdit(goal: string, steps: TaskPlan['steps']): TaskPlan {
  const plan = planSchema.parse({goal, steps});
  if (new Set(plan.steps.map(step => step.id)).size !== plan.steps.length)
    throw new Error('Task step IDs must be unique.');
  if (plan.steps.some(step => step.status === 'completed' && !step.evidence?.trim()))
    throw new Error('Completed steps require verification evidence.');
  return clonePlan(plan);
}
